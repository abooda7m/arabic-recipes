async function seed() {
  try {
    await mongoose.connect(process.env.MONGODB_URI || 'mongodb://localhost:27017/arabic-recipes');
    console.log('Connected to MongoDB');

    // Clear existing
    await User.deleteMany({});
    await Recipe.deleteMany({});
    console.log('Cleared old data');

    // Create admin user
    const user = await User.create(SEED_USER);
    console.log(`Created user: ${user.username}`);

    // Create recipes
    const recipesWithAuthor = RECIPES.map((r) => ({ ...r, author: user._id }));
    await Recipe.insertMany(recipesWithAuthor);
    console.log(`Seeded ${RECIPES.length} recipes`);

    console.log('\nSeed complete!');
    console.log('Login: admin@recipes.com | Password: admin123');
    process.exit(0);
  } catch (err) {
    console.error('Seed error:', err.message);
    process.exit(1);
  }
}

seed();
